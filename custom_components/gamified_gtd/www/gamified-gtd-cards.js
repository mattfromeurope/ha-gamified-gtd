// person.alex -> "alex" (used to build sensor entity ids).
function personName(person) {
  return (person || "").replace(/^person\./, "").replace(/\./g, "_");
}
// person entity id + suffix -> sensor entity id, e.g. sensor.alex_level.
function sensorId(person, suffix) {
  return `sensor.${personName(person)}_${suffix}`;
}
// Resolve the person entity of the currently logged-in HA user (via user_id attr).
function mePerson(hass) {
  const uid = hass && hass.user && hass.user.id;
  if (!uid) return null;
  const p = Object.values(hass.states).find(
    (s) => s.entity_id.startsWith("person.") && s.attributes && s.attributes.user_id === uid
  );
  return p ? p.entity_id : null;
}
// All person.* / zone.* entity ids (for the assignment / location selects).
function entitiesOf(hass, domain) {
  return Object.keys(hass.states).filter((e) => e.startsWith(domain + ".")).sort();
}

// Icon helper lookup order: user drop-in <kind>/<id>.png (original FNV icons if the
// user supplies them) -> embedded placeholder PLACEHOLDERS['<kind>/<id>'] (shipped
// Vault-Boy-style data-URI svg) -> embedded generic PLACEHOLDERS['<kind>/placeholder>']
// -> text glyph fallback (the <img> removes itself). On successful load the text
// fallback is removed. The remaining candidates are carried in data-candidates so
// the @error chain is explicit and order-safe.
function icon(kind, id, fallback, big) {
  const candidates = [
    `${ICONS}/${kind}/${id}.png`,
    PLACEHOLDERS[`${kind}/${id}`],
    PLACEHOLDERS[`${kind}/placeholder`],
  ].filter(Boolean);
  return html`<span class="gicon ${big ? "big" : ""}"
    ><span class="gicon-fb">${fallback}</span
    ><img
      src="${candidates[0]}"
      data-candidates="${candidates.slice(1).join("|")}"
      alt=""
      @error=${(e) => {
        const rest = (e.target.dataset.candidates || "").split("|").filter(Boolean);
        if (rest.length > 0) {
          e.target.dataset.candidates = rest.slice(1).join("|");
          e.target.src = rest[0]; // next candidate (data URIs never 404)
        } else {
          e.target.remove(); // no image at all -> text fallback stays
        }
      }}
      @load=${(e) => {
        const fb = e.target.previousElementSibling;
        if (fb) fb.remove();
      }}
  /></span>`;
}

