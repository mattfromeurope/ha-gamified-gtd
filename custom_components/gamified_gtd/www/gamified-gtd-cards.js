// GUI config editor for the tasks card — HA shows it in the card's edit dialog and
// listens for "config-changed" (bubbles/composed) to store the new config.
class GamifiedGTDTasksEditor extends LitElement {
  static get properties() {
    return { hass: {}, config: {} };
  }
  // HA's card-editor wrapper pushes the raw stored card config into the editor element:
  // newer frontends call setConfig(value), older ones assign .config directly —
  // support both, so the editor always sees the current YAML config.
  setConfig(config) {
    this.config = config;
  }
  _fire(config) {
    this.dispatchEvent(
      new CustomEvent("config-changed", { detail: { config }, bubbles: true, composed: true })
    );
  }
  render() {
    // Merge the raw stored config over the shared defaults — the editor always fires a
    // COMPLETE config, so no option silently disappears from the YAML on change.
    const c = { ...tasksCardDefaults(), ...(this.config || {}) };
    const persons = entitiesOf(this.hass, "person");
    const lists = [
      { id: "all", label: "All lists" },
      { id: "completed", label: "Completed (from all lists)" },
      ...Object.entries(LISTS).map(([k, l]) => ({ id: k, label: l.label })),
    ];
    const assignedOpts = [
      { id: "all", label: "Everyone" },
      { id: "me", label: "Only me (logged-in user)" },
      ...persons.map((p) => ({ id: p, label: p })),
    ];
    const sorts = [
      ["created", "Created (default)"],
      ["due", "Due date"],
      ["priority", "Priority"],
      ["title", "Title"],
    ];
    const details = c.details || TASK_DETAIL_FIELDS.map((f) => f.id);
    return html`
      <div class="ed">
        <label>Title</label>
        <input type="text" .value=${c.title || ""} @change=${(e) => this._fire({ ...c, title: e.target.value })} />
        <label>List</label>
        <select .value=${c.list || "all"} @change=${(e) => this._fire({ ...c, list: e.target.value })}>
          ${lists.map((l) => html`<option value=${l.id}>${l.label}</option>`)}
        </select>
        <label>Assigned to</label>
        <select .value=${c.assigned || "all"} @change=${(e) => this._fire({ ...c, assigned: e.target.value })}>
          ${assignedOpts.map((o) => html`<option value=${o.id}>${o.label}</option>`)}
        </select>
        <label>Sort by</label>
        <select .value=${c.sort || "created"} @change=${(e) => this._fire({ ...c, sort: e.target.value })}>
          ${sorts.map(([v, l]) => html`<option value=${v}>${l}</option>`)}
        </select>
        <label class="chk"><input type="checkbox" .checked=${c.show_completed === true}
          @change=${(e) => this._fire({ ...c, show_completed: e.target.checked })} /> Show completed tasks</label>
        <label>Details shown directly on the row</label>
        ${TASK_DETAIL_FIELDS.map((f) => html`
          <label class="chk"><input type="checkbox" .checked=${details.includes(f.id)}
            @change=${(e) => {
              const cur = new Set(details);
              if (e.target.checked) cur.add(f.id);
              else cur.delete(f.id);
              this._fire({ ...c, details: [...cur] });
            }} /> ${f.label}</label>`)}
      </div>`;
  }
  static get styles() {
    return cardCss;
  }
}
defineCard("gamified-gtd-tasks-editor", GamifiedGTDTasksEditor);

