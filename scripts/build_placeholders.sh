#!/usr/bin/env bash
# Regenerates www/gamified-gtd-placeholders.js: the shipped Vault-Boy-style
# placeholder SVGs (www/gamified_gtd_icons/<kind>/*.svg) embedded as data URIs.
#
# Why: the cards try the user's drop-in <id>.png first and fall back to a
# placeholder image. Embedding the placeholders as data URIs makes the fallback
# independent of HTTP 404s / service-worker caches — the image is always there.
# Run this after adding/changing placeholder SVGs; the output is checked in
# (HA serves www/ directly, users never run a build).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ICONS="$REPO_ROOT/custom_components/gamified_gtd/www/gamified_gtd_icons"
OUT="$REPO_ROOT/custom_components/gamified_gtd/www/gamified-gtd-placeholders.js"

node - "$ICONS" "$OUT" <<'NODE_EOF'
const fs = require("fs");
const path = require("path");
const [iconsDir, out] = process.argv.slice(2);
const entries = {};
for (const kind of fs.readdirSync(iconsDir)) {
  const dir = path.join(iconsDir, kind);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith(".svg")) continue;
    const id = file.slice(0, -4);
    const data = fs.readFileSync(path.join(dir, file)).toString("base64");
    entries[`${kind}/${id}`] = `data:image/svg+xml;base64,${data}`;
  }
}
const js =
  "/* GENERATED by scripts/build_placeholders.sh — do not edit by hand.\n" +
  " * Shipped Vault-Boy-style placeholder icons as data URIs, keyed '<kind>/<id>'.\n" +
  " * The cards try the user drop-in <kind>/<id>.png first, then this placeholder.\n" +
  " */\n" +
  "export const PLACEHOLDERS = " + JSON.stringify(entries, null, 1) + ";\n";
fs.writeFileSync(out, js);
console.log("wrote " + out + " with " + Object.keys(entries).length + " placeholders");
NODE_EOF
